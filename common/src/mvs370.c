unsigned char mvs_a2e(int c) { return mvs_a2e_tab[c & 0xff]; }
unsigned char mvs_e2a(int c) { return mvs_e2a_tab[c & 0xff]; }

void mvs_name8(unsigned char d[8], const char *s)
{
    int i, done = 0;
    for (i = 0; i < 8; i++) {
        if (!done && (!s || !s[i])) done = 1;
        d[i] = done ? 0x40 : mvs_a2e((unsigned char)s[i]);
    }
}

const char *mvs_nm(const unsigned char n[8])
{
    static char b[9];
    int i;
    for (i = 0; i < 8; i++) {
        unsigned char a = mvs_e2a(n[i]);
        b[i] = (a >= 0x20 && a < 0x7f) ? (char)a : '?';
    }
    b[8] = 0;
    for (i = 7; i >= 0 && b[i] == ' '; i--) b[i] = 0;
    return b;
}

/* ---- whole-file read ---- */
unsigned char *mvs_read_file(const char *path, long *len)
{
    FILE *f = fopen(path, "rb");
    unsigned char *b;
    long n;
    if (!f) return NULL;
    if (fseek(f, 0, SEEK_END) != 0) { fclose(f); return NULL; }
    n = ftell(f);
    if (n < 0) { fclose(f); return NULL; }
    rewind(f);
    b = malloc((size_t)n + 1);
    if (!b) { fclose(f); return NULL; }
    if (n > 0 && fread(b, 1, (size_t)n, f) != (size_t)n) { free(b); fclose(f); return NULL; }
    fclose(f);
    b[n] = 0;
    *len = n;
    return b;
}

/* ---- CKD count field: F + MBBCCHHR(M,BB,CC,HH,R) + KL + DL ---- */
void mvs_put_count(unsigned char *p, int cc, int hh, int r, int kl, int dl)
{
    p[0] = 0;                                   /* F flag */
    p[1] = 0; p[2] = 0; p[3] = 0;               /* M(1) + BB(2) */
    mvs_put16(p + 4, cc); mvs_put16(p + 6, hh); p[8] = (unsigned char)r;
    p[9] = (unsigned char)kl; mvs_put16(p + 10, dl);
}

/* ---- NETDATA ---- */
void mvs_tu(unsigned char *b, long *p, int key, const unsigned char *val, int len)
{
    mvs_put16(b + *p, key); *p += 2;
    mvs_put16(b + *p, 1);   *p += 2;
    mvs_put16(b + *p, len); *p += 2;
    memcpy(b + *p, val, (size_t)len); *p += len;
}

void mvs_tui(unsigned char *b, long *p, int key, long v, int n)
{
    unsigned char t[4];
    mvs_wrval(t, v, n);
    mvs_tu(b, p, key, t, n);
}

void mvs_tus(unsigned char *b, long *p, int key, const char *s)
{
    unsigned char t[44];
    int i, n = (int)strlen(s);
    if (n > 44) n = 44;
    for (i = 0; i < n; i++) t[i] = mvs_a2e((unsigned char)s[i]);
    mvs_tu(b, p, key, t, n);
}

void mvs_tu_dsname(unsigned char *b, long *p, const char *dsn)
{
    const char *s = dsn, *q;
    int nq = 1, i;
    for (q = dsn; *q; q++) if (*q == '.') nq++;
    mvs_put16(b + *p, INM_DSNAM); *p += 2;
    mvs_put16(b + *p, nq);        *p += 2;
    for (;;) {
        int qn = 0;
        while (s[qn] && s[qn] != '.') qn++;
        mvs_put16(b + *p, qn); *p += 2;
        for (i = 0; i < qn; i++) b[(*p)++] = mvs_a2e((unsigned char)s[i]);
        if (!s[qn]) break;
        s += qn + 1;
    }
}

long mvs_inmr_hdr(unsigned char *r, int n)
{
    r[0] = 0xc9; r[1] = 0xd5; r[2] = 0xd4; r[3] = 0xd9; r[4] = 0xf0;   /* 'INMR0' */
    r[5] = (unsigned char)(0xf0 + n);
    return 6;
}

void mvs_netdata_seg(unsigned char *o, long *p, const unsigned char *rec,
                     long len, int control)
{
    long off = 0;
    int ctl = control ? NETSEG_CTL : 0;
    do {
        long n = len - off;
        int flags;
        if (n > 253) n = 253;
        flags = ctl | (off == 0 ? NETSEG_FIRST : 0)
                    | (off + n >= len ? NETSEG_LAST : 0);
        o[(*p)++] = (unsigned char)(n + 2);
        o[(*p)++] = (unsigned char)flags;
        memcpy(o + *p, rec + off, (size_t)n); *p += n;
        off += n;
    } while (off < len);
}
